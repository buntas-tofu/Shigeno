#!/usr/bin/env python3
"""ignored-code.py: the silent-exclusion gate.

WHY THIS EXISTS. An ignore rule fails in one direction only, and it is the
quiet one. An over-tracked file shows up in a diff and costs one revert. An
over-ignored file produces no error, no warning, and no line in the status
output; it surfaces on the day something reaches for it and finds nothing.
The asymmetry is the whole argument for this gate.

The shapes it catches, all one family of mistake:

  1. A room of raw records that no move ever carried, because every file in it
     was ignored and no tool that works through the version control system can
     see an ignored file at all.
  2. A directory ignored whole under a comment that promised the contents
     would be promoted to tracked later. The promotion never ran, and a
     document that cited a script living inside it named a file the tool
     could not read.
  3. A depth rule used where a content rule was meant, so packs of files
     tracked their manifest and dropped the data dictionary that explains
     them.

None of those announced itself. Each was found by someone going to look. This
gate goes to look on a schedule.

WHAT IT DOES. For every repository under the configured root, it lists the
files the version control system is ignoring that are code or documentation,
names the exact rule doing the ignoring, and separates the accounted-for from
the unaccounted-for. The allowlist below carries a reason per entry, because
an exclusion without a stated reason is the thing that rots.

WHAT IT DELIBERATELY DOES NOT DO. It does not flag data, models, caches,
dependency trees, or vendored upstream clones, all of which are ignored
correctly and in volume. It has no opinion on whether an unaccounted file
should be tracked. It reports that a decision was made silently and lets a
person make it out loud. Exit code is always 0, the same contract as
family-drift.py.

GOVERNING PRINCIPLE. Exposure is a property of the remote, not of an ignore
line. An ignore rule answers what a file IS. Whether the repository can be
published is answered by where it pushes. Keep the two questions apart.

Configuration:
  REPO_ROOT  directory to scan for repositories. Default: $HOME/code

Floor: no em dashes, no ellipses. This file is an artifact.
"""

import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(os.environ.get("REPO_ROOT", Path.home() / "code"))

# What counts as code or documentation. Everything else is presumed data.
WATCHED = re.compile(
    r"\.(py|sh|bash|R|r|sas|sql|js|ts|jsx|tsx|go|rs|c|h|cpp|java|kt|swift"
    r"|typ|md|rst|toml|cfg|ini|service|timer)$"
)

# Ignored on purpose, each with the reason it is not a finding. A pattern here
# is a claim that someone decided this deliberately, so it carries the
# decision. Extend this list for your project; an entry with no reason is the
# entry that rots.
ALLOWED = [
    (r"(^|/)\.venv/", "virtualenv, rebuilt from a lockfile"),
    (r"(^|/)site-packages/", "installed dependency tree"),
    (r"(^|/)node_modules/", "installed dependency tree"),
    (r"(^|/)__pycache__/|\.pyc$", "bytecode cache"),
    (r"(^|/)(build|dist|out|target|cmake-build[^/]*|CMakeFiles)/", "build tree, regenerated by the toolchain"),
    (r"(^|/)\.(pytest|mypy|ruff)_cache/|(^|/)\.tox/", "tool cache, self-ignoring"),
    (r"(^|/)\.secrets/", "credentials, and they never enter the version control system"),
    (r"(^|/)receipts/", "run receipts, regenerated by the tools"),
    # Vendored upstream clones. Provenance is pinned in the owning room's
    # ignore file; committing a nested clone leaves a broken gitlink.
    (r"(^|/)(vendor|third_party|repos)/", "vendored upstream clones, provenance pinned where they live"),
    # Raw captured layers. Gathered copies and captured conversation, which
    # the room's own contract says are never rewritten and never versioned.
    (r"(^|/)(exports|sediment|logs|telemetry)/", "raw captured layers, unversioned by contract"),
]


def repos():
    """Every repository under the root. Vendored clones carry their own git
    directory and are skipped, along with anything inside a dependency tree."""
    out = []
    for g in sorted(ROOT.glob("**/.git")):
        r = g.parent
        rel = str(r.relative_to(ROOT)) if r != ROOT else "."
        if any(re.search(p, rel + "/") for p, _ in ALLOWED if "vendored" in _ or "pinned" in _):
            continue
        if "/.venv/" in str(r) or "node_modules" in str(r):
            continue
        out.append((rel, r))
    return out


def ignored_rule(repo, path):
    """Which line of which file is ignoring this. Makes a finding actionable."""
    p = subprocess.run(["git", "-C", str(repo), "check-ignore", "-v", path],
                       capture_output=True, text=True)
    if p.returncode != 0 or not p.stdout.strip():
        return "unknown"
    src, line, pat, _ = (p.stdout.strip().split("\t")[0] + ":::").split(":", 3)[:4]
    return f"{src}:{line} `{pat}`"


def main():
    accounted, findings = 0, []
    for rel, repo in repos():
        p = subprocess.run(
            ["git", "-C", str(repo), "ls-files", "--others", "--ignored", "--exclude-standard"],
            capture_output=True, text=True, timeout=120)
        for f in p.stdout.splitlines():
            if not WATCHED.search(f):
                continue
            reason = next((why for pat, why in ALLOWED if re.search(pat, f)), None)
            if reason:
                accounted += 1
            else:
                findings.append((rel, f, ignored_rule(repo, f)))

    print("# Ignored-code gate\n")
    print(f"**Verdict: {len(findings)} unaccounted, {accounted} accounted for.** "
          f"{len(repos())} repos scanned.\n")
    print("Code or documentation that is being ignored. Over-ignoring fails silently, "
          "so this reports the silence; it has no opinion on whether a file should be "
          "tracked, only that the choice was never stated.\n")

    if not findings:
        print("## Unaccounted\n\nNone. Every ignored code file matches an allowlist "
              "entry with a stated reason.\n")
    else:
        print("## Unaccounted\n")
        by_repo = {}
        for rel, f, rule in findings:
            by_repo.setdefault(rel, []).append((f, rule))
        for rel in sorted(by_repo):
            print(f"### `{rel}`\n")
            for f, rule in sorted(by_repo[rel]):
                print(f"- `{f}`  ignored by {rule}")
            print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
